def render(text, bold=False, scale=1):
    """liefert Liste von Zeilen (Liste von 0/1)"""
    rows = [[] for _ in range(9)]
    for i, ch in enumerate(text):
        gl = G[ch]
        for r in range(9):
            rows[r] += [1 if c == '#' else 0 for c in gl[r]]
            if i != len(text) - 1:
                rows[r].append(0)
    if bold:
        rows = [[r[i] | (r[i-1] if i > 0 else 0) for i in range(len(r))] + [r[-1]] for r in rows]
    # leere Unterlaengen abschneiden, wenn nicht gebraucht
    while len(rows) > 7 and not any(rows[-1]):
        rows.pop()
    if scale > 1:
        rows = [[p for p in r for _ in range(scale)] for r in rows for _ in range(scale)]
    return rows
