# Proportionale Pixelschrift, 9 Zeilen (7 ueber Grundlinie, 2 Unterlaenge)
G = {}
def g(ch, s):
    s = s[1:] if s.startswith('\n') and not s.startswith('\n\n') else s
    rows = s.split('\n')
    rows = [r.rstrip() for r in rows]
    w = max(len(r) for r in rows)
    rows = [r.ljust(w, '.') for r in rows]
    while len(rows) < 9:
        rows.append('.' * w)
    G[ch] = rows

