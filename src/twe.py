# Zeileneditor: Adresszeile und Formularfeld mit Schreibmarke (Pfeile, Wahl-/Apfel-Pfeile,
# Strg-A/E, Entf, Strg-D, Einfuegen in der Mitte)
from twbase import *
import twbase
from marisim import Marinetti
cpu = boot(); cpu.mari = Marinetti(net)
settle()
OPT, APL = 0x0800, 0x0100
click(101, 193)
typ('frogfind.com/zwei')
check(bstr(0xF800) == b'frogfind.com/zwei' and w('ADRCUR') == 17, 'getippt, Schreibmarke am Ende')
for i in range(5): key(0x08)
check(w('ADRCUR') == 12, 'Pfeil links x5 (%d)' % w('ADRCUR'))
typ('X')
check(bstr(0xF800) == b'frogfind.comX/zwei' and w('ADRCUR') == 13, 'in der Mitte eingefuegt: %r' % bstr(0xF800))
key(0x7F)
check(bstr(0xF800) == b'frogfind.com/zwei', 'Entf loescht davor')
key(0x01)
check(w('ADRCUR') == 0, 'Strg-A: Anfang')
key(0x05)
check(w('ADRCUR') == 17, 'Strg-E: Ende')
key(0x08, OPT)
check(w('ADRCUR') == 13, 'Wahl-Pfeil links: Wortanfang "zwei" (%d)' % w('ADRCUR'))
key(0x08, OPT)
check(w('ADRCUR') == 9, 'nochmal: "com" (%d)' % w('ADRCUR'))
key(0x15, OPT)
check(w('ADRCUR') == 13, 'Wahl-Pfeil rechts: hinter "com/" (%d)' % w('ADRCUR'))
key(0x08, APL)
check(w('ADRCUR') == 0, 'Apfel-Pfeil links: Anfang')
key(0x15, APL)
check(w('ADRCUR') == 17, 'Apfel-Pfeil rechts: Ende')
render(cpu, 'twe_a.png', 3)
key(0x0D)
check(bstr(0xFC00) == b'Zwei', 'Seite geladen')
# langer Text: Schreibmarke sichtbar
typ('http://frogfind.com/' + 'a' * 60)
for i in range(70): key(0x08)
render(cpu, 'twe_b.png', 3)
check(w('ADRCUR') == 10, 'lange Adresse, Schreibmarke vorn (%d)' % w('ADRCUR'))
print('ALLES OK' if twbase.ok else 'FAIL Zeileneditor')
