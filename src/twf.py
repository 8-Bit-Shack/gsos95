# FujiNet am SmartPort (nachgebildet): Erkennung, http ueber N:TCP, https ueber N:HTTPS
# (Karte verschluesselt), Formular per POST ueber https, Telnet, Fehler
from twbase import *
import twbase
from fujisim import FujiNet
fn = FujiNet(net)
net.pages[('10.1.1.5', 443, '/form')] = b'<title>Form</title><form method="post" action="/post"><input name="q" value="abc"><input type="submit" value="Los"></form>'
net.pages[('10.1.1.5', 443, '/post')] = lambda body: b'<title>Antwort</title><p>Danke ' + body + b'</p>'
cpu = boot(); fn.install(cpu)
settle()
click(101, 193)
typ('frogfind.com'); key(0x0D)
check(w('NCARD') == 3, 'FujiNet erkannt (NCARD=%d, Einheit %d)' % (w('NCARD'), w('FNUNIT')))
check(w('FNUNIT') == 3, 'Geraet NETWORK = Einheit 3')
check(('fopen', 12, 'N:TCP://frogfind.com:80/') in net.log, 'http als N:TCP://, Name geht an die Karte')
check(bstr(0xFC00) == b'FrogFind!' and txt().count(b'Welt') == 400, 'HTTP ueber FujiNet (Stuecke zu 512)')
check(getattr(cpu, 'timeset', None) is not None and len(twbase.TIMEQ) >= 1, 'Uhr per Time-Dienst (TCP 37) gestellt: %r' % (getattr(cpu, 'timeset', None),))
typ('frogfind.com/redir'); key(0x0D)
check(bstr(0xFC00) == b'Zwei', 'Weiterleitung')
typ('https://secure.test'); key(0x0D)
check(('fopen', 12, 'N:HTTPS://secure.test/') in net.log, 'https als N:HTTPS:// (Modus 12)')
check(bstr(0xFC00) == b'Sicher', 'HTTPS ueber die Karte: %r' % bstr(0xFC00))
req = [r for r in net.requests if r[0] == ('10.1.1.5', 443)]
check(req and req[-1][1][3] == [b'Content-Type'], 'Inhaltstyp gesammelt: %r' % (req[-1][1] if req else None,))
key(0x0A); key(0x0B)
click(cpu.rd16(ADDR + lbl['wrecs'] + 2) + 14, cpu.rd16(ADDR + lbl['wrecs'] + 4) + 31 + 10 * 2 + 4)
check(bstr(0xFD80) == b'https://secure.test/zwei' and bstr(0xFC00) == b'Zwei', 'relativer Link bleibt https: %r' % bstr(0xFD80))
typ('https://secure.test/nix'); key(0x0D)
check(b'404' in txt(), '404 ueber https: %r' % txt()[:60])
typ('https://secure.test/form'); key(0x0D)
check(bstr(0xFC00) == b'Form', 'Formularseite')
wx = cpu.rd16(ADDR + lbl['wrecs'] + 2); wy = cpu.rd16(ADDR + lbl['wrecs'] + 4)
click(wx + 8 + 10, wy + 31 + 4); key(0x0D)
check(('fopen', 13, 'N:HTTPS://secure.test/post') in net.log, 'POST ueber https: Modus 13')
check(bstr(0xFC00) == b'Antwort' and b'Danke q=abc' in txt(), 'POST-Daten an die Karte, Antwort: %r' % txt()[:40])
typ('gibtsnicht.test'); key(0x0D)
check(b'lehnt' in txt() or b'nicht' in txt(), 'unbekannter Rechner: Fehlerseite')
typ('telnet://bbs.example'); key(0x0D)
idle()
r = ''.join(term_rows())
check(w('TNON') == 1 and 'Willkommen in der Mailbox' in r, 'Telnet ueber FujiNet')
check(('fopen', 12, 'N:TCP://bbs.example:23/') in net.log, 'Telnet als N:TCP://bbs.example:23/')
for ch in 'gast': key(ord(ch))
key(0x0D); idle(4)
check(b''.join(twbase.TIN).startswith(b'gast'), 'Tasten gesendet')
key(0x1B, 0x0100); idle(4)
check(w('TNON') == 0, 'Telnet beendet')
render(cpu, 'twf_a.png', 3)
typ('about:net'); key(0x0D)
check(b'FujiNet' in txt() and b'auf der Karte' in txt(), 'about:net: %r' % txt()[:120])
print('ALLES OK' if twbase.ok else 'FAIL FujiNet')
