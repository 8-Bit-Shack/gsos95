# v2.18: MS-DOS-Eingabeaufforderung (about:msdos, Start > Programme > Werkzeuge > MS-DOS)
from twbase import *
import twbase
from t3 import FILES, FS
FILES[':SYSTEM.DISK:SYSTEM:START'] = b'Zeile eins\rZeile zwei\r\nZeile drei\n'
def scr(n=25): return term_rows(n)
def show(): print('\n'.join(r.rstrip() for r in scr() if r.strip()))
def cmd(t): typ(t); key(0x0D)
def has(t): return any(t in r for r in scr())
cpu = boot(); settle()
key(9); key(0x15); key(0x15); key(0x0A); key(0x0A); key(0x0D)   # Programme > Werkzeuge > MS-DOS
check(w('VTON') == 1 and w('DOSON') == 1, 'Start > Werkzeuge > MS-DOS: Vollbild')
check(has('MS-DOS-Eingabeaufforderung') and scr()[4].startswith('C:\\>'), 'Begruessung und C:\\>')
render(cpu, 'tdos_0.png', 3)
cmd('ver'); check(has('[Version 2.18.0]'), 'VER')
cmd('dir')
show()
check(has('SYSTEM.DISK') and has('<DIR>') and has('BASIC.SYSTEM') and has('15.11.2026  13:42'), 'DIR: Volume, Ordner, Dateien, Datum')
check(has('10.000') and has('Datei(en)') and has('Verzeichnis(se)'), 'DIR: Groesse mit Punkt, Summen')
render(cpu, 'tdos_1.png', 3)
cmd('cls'); check(scr()[0].startswith('C:\\>') , 'CLS')
cmd('cd system'); cmd('cd'); check(has('C:\\SYSTEM\r') or any(r.rstrip() == 'C:\\SYSTEM' for r in scr()), 'CD SYSTEM')
check(any(r.startswith('C:\\SYSTEM>') for r in scr()), 'Eingabe zeigt Pfad')
cmd('type start'); check(has('Zeile eins') and has('Zeile zwei') and has('Zeile drei'), 'TYPE mit CR, CRLF, LF')
cmd('cd..'); check(any(r.startswith('C:\\>') for r in scr()[-6:]) or has('C:\\>'), 'CD..')
cmd('cd gibtsnicht'); check(has('Ungültiges Verzeichnis'), 'CD auf Unbekanntes')
cmd('cls'); cmd('type readme')
check(has('-- Fortsetzung'), 'TYPE: Pause nach einer Seite')
key(ord(' ')); check(has('-- Fortsetzung'), 'naechste Seite')
key(0x1B); check(has('^C'), 'Esc bricht ab')
check(w('DSMODE_') == 0, 'wieder Eingabe')
cmd('cls'); cmd('date'); cmd('time'); cmd('mem'); show()
check(has('Aktuelles Datum: So 15.11.2026'), 'DATE')
check(has('Aktuelle Uhrzeit: 09:42:05,00'), 'TIME')
check(has('655.360 Bytes konventioneller') and has('1.234.567 Bytes frei'), 'MEM')
cmd('cls'); cmd('del readme'); cmd('format c:'); cmd('win'); cmd('quatsch'); cmd('a:'); cmd('echo Hallo Welt'); show()
check(has('Zugriff verweigert') and has('Lieber nicht') and has('läuft bereits') and has('Befehl oder Dateiname') and has('Laufwerk A') and has('Hallo Welt'), 'DEL, FORMAT, WIN, Unbekanntes, A:, ECHO')
check(':SYSTEM.DISK:README' in FILES, 'nichts geloescht')
cmd('cls'); cmd('help'); check(has('COLOR') and has('TYPE'), 'HELP')
key(0x0B); check(scr()[-1].startswith('C:\\>help') or any(r.startswith('C:\\>help') for r in scr()), 'Pfeil hoch: letzter Befehl')
key(0x1B); cmd('color 1e'); render(cpu, 'tdos_2.png', 3)
cmd('exit')
check(w('VTON') == 0 and w('DOSON') == 0 and w('WIN') != 21, 'EXIT schliesst das Fenster')
render(cpu, 'tdos_3.png', 3)
# Startmenue-Bild
key(9); key(0x15); key(0x15); render(cpu, 'tdos_m.png', 3); key(0x1B); key(0x1B); key(0x1B)
# aus dem Browser: about:msdos, EXIT laesst das Fenster offen
key(0x1B)
key(9); key(0x15); key(0x0A); key(0x15); key(0x0D)
print('WIN', w('WIN'))
typ('about:msdos'); key(0x0D)
check(w('DOSON') == 1, 'about:msdos im Browser')
cmd('exit')
check(w('DOSON') == 0 and w('WIN') == 21, 'EXIT: Browser bleibt offen (WIN %d)' % w('WIN'))
render(cpu, 'tdos_4.png', 3)
print('ALLES OK' if twbase.ok else 'FAIL')
